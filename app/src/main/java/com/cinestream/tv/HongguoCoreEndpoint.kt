package com.cinestream.tv

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.runInterruptible
import org.json.JSONObject
import java.io.ByteArrayOutputStream
import java.io.IOException
import java.net.HttpURLConnection
import java.net.URL

/** Independent readiness/status bridge only. Does not start an engine or request media preparation. */
internal class HongguoCoreEndpoint private constructor(
    val port: Int,
    private val instanceId: String,
    private val expectedVersion: String,
) {
    val baseUrl: String get() = "http://127.0.0.1:$port/"
    class Response(val status: Int, val body: ByteArray)

    /** The status route, not the health route, carries the child identity and version. */
    suspend fun verify(transport: (String) -> Response = ::getStatus) = runInterruptible(Dispatchers.IO) {
        val response = try { transport("${baseUrl}api/v1/status") }
        catch (_: IOException) { throw IOException("Hongguo local engine status unavailable") }
        if (response.status != 200) throw IOException("Hongguo local engine status HTTP ${response.status}")
        requireMatchingStatus(response.body)
    }

    internal fun requireMatchingStatus(bytes: ByteArray) {
        if (bytes.isEmpty() || bytes.size > MAX_STATUS_BYTES) throw IOException("Invalid Hongguo local engine status")
        val matches = try {
            val json = JSONObject(String(bytes, Charsets.UTF_8))
            json.optBoolean("ok") && json.optString("service") == "hongguo-tv-core" &&
                json.optString("instance_id") == instanceId && json.optString("version") == expectedVersion
        } catch (_: Exception) { false }
        if (!matches) throw IOException("Hongguo local engine identity or version mismatch")
    }

    override fun toString() = "HongguoCoreEndpoint(port=$port, identity=redacted)"

    companion object {
        private const val MAX_STATUS_BYTES = 64 * 1024
        private val ready = Regex("^HONGGUO_TV_READY ([0-9]{1,5}) ([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})$")

        /** Supply an instance ID generated by our own future child launcher, never from a discovered port. */
        fun fromReadyLine(line: String, expectedInstanceId: String, expectedVersion: String): HongguoCoreEndpoint? {
            if (line.length > 128 || expectedVersion.isBlank() || expectedVersion.length > 96) return null
            val match = ready.matchEntire(line) ?: return null
            if (match.groupValues[2] != expectedInstanceId) return null
            val port = match.groupValues[1].toIntOrNull()?.takeIf { it in 1..65535 } ?: return null
            return HongguoCoreEndpoint(port, expectedInstanceId, expectedVersion)
        }

        private fun getStatus(address: String): Response {
            // Only addresses constructed from a validated readiness line reach this transport.
            val connection = URL(address).openConnection() as HttpURLConnection
            try {
                connection.instanceFollowRedirects = false
                connection.connectTimeout = 2000; connection.readTimeout = 2000
                connection.requestMethod = "GET"
                connection.setRequestProperty("Accept", "application/json")
                val status = connection.responseCode
                if (status != 200) return Response(status, byteArrayOf())
                val output = ByteArrayOutputStream()
                connection.inputStream.use { stream ->
                    val buffer = ByteArray(4096)
                    while (true) {
                        if (Thread.currentThread().isInterrupted) throw InterruptedException()
                        val count = stream.read(buffer)
                        if (count < 0) break
                        if (output.size() + count > MAX_STATUS_BYTES) throw IOException("Hongguo local engine status too large")
                        output.write(buffer, 0, count)
                    }
                }
                return Response(status, output.toByteArray())
            } finally { connection.disconnect() }
        }
    }
}
